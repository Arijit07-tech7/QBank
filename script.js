/* =========================================================
   LOAD SEMESTERS
========================================================= */

function loadSemesters() {

    selectedSemester = "";

    selectedSubject = "";


    if (elementExists(subjectOptions)) {

        subjectOptions.innerHTML = "";

    }


    if (elementExists(subjectStep)) {

        subjectStep.classList.add(
            "disabled-step"
        );

    }


    if (elementExists(semesterStep)) {

        semesterStep.classList.remove(
            "disabled-step"
        );

    }


    if (!IT_CURRICULUM[selectedYear]) {

        showToast(
            "No academic data available for this year."
        );

        return;

    }


    const semesters =
        Object.keys(
            IT_CURRICULUM[selectedYear]
        );


    if (elementExists(semesterOptions)) {

        semesterOptions.innerHTML = "";

    }


    semesters.forEach(
        semester => {

            const button =
                document.createElement(
                    "button"
                );


            button.type = "button";


            button.className =
                "filter-option semester-option";


            button.dataset.semester =
                semester;


            const subjectCount =
                IT_CURRICULUM[selectedYear]
                    [semester]
                    .length;


            button.innerHTML = `

                <strong>
                    ${semester}
                </strong>

                <small>
                    ${subjectCount} subjects
                </small>

            `;


            button.addEventListener(
                "click",
                () => {

                    document
                        .querySelectorAll(
                            ".semester-option"
                        )
                        .forEach(btn => {

                            btn.classList.remove(
                                "selected"
                            );

                        });


                    button.classList.add(
                        "selected"
                    );


                    selectedSemester =
                        semester;


                    loadSubjects();

                }
            );


            semesterOptions.appendChild(
                button
            );

        }
    );


    semesterStep.scrollIntoView({

        behavior: "smooth",

        block: "center"

    });

}


/* =========================================================
   LOAD SUBJECTS
========================================================= */

function loadSubjects() {

    selectedSubject = "";


    if (elementExists(subjectStep)) {

        subjectStep.classList.remove(
            "disabled-step"
        );

    }


    if (elementExists(subjectOptions)) {

        subjectOptions.innerHTML = "";

    }


    const subjects =
        IT_CURRICULUM[selectedYear]
            ?. [selectedSemester];


    if (!subjects) {

        showToast(
            "No subjects found."
        );

        return;

    }


    subjects.forEach(
        subject => {

            const button =
                document.createElement(
                    "button"
                );


            button.type = "button";


            button.className =
                "subject-selector";


            button.dataset.code =
                subject.code;


            button.innerHTML = `

                <div class="subject-code">
                    ${subject.code}
                </div>

                <div class="subject-selector-info">

                    <strong>
                        ${subject.name}
                    </strong>

                    <span>
                        ${subject.type}
                    </span>

                </div>

                <div class="subject-arrow">
                    →
                </div>

            `;


            button.addEventListener(
                "click",
                () => {

                    document
                        .querySelectorAll(
                            ".subject-selector"
                        )
                        .forEach(btn => {

                            btn.classList.remove(
                                "selected"
                            );

                        });


                    button.classList.add(
                        "selected"
                    );


                    selectedSubject =
                        subject.code;


                    showPapers(subject);

                }
            );


            subjectOptions.appendChild(
                button
            );

        }
    );


    subjectStep.scrollIntoView({

        behavior: "smooth",

        block: "center"

    });

}


/* =========================================================
   SHOW PAPERS
========================================================= */

function showPapers(subject) {

    const papers =
        PDF_DATABASE[
            subject.code
        ] || [];


    if (elementExists(resultCount)) {

        resultCount.textContent =
            `${papers.length} ${
                papers.length === 1
                    ? "Paper"
                    : "Papers"
            }`;

    }


    /* -----------------------------------------------------
       NO PDF
    ----------------------------------------------------- */

    if (!papers.length) {

        if (elementExists(paperResults)) {

            paperResults.innerHTML = `

                <div class="no-papers">

                    <div class="no-papers-icon">
                        PDF
                    </div>

                    <h3>
                        No question paper uploaded yet
                    </h3>

                    <p>

                        No PDF is currently available
                        for

                        <strong>
                            ${escapeHTML(
                                subject.name
                            )}
                        </strong>.

                    </p>

                    <div class="paper-path">

                        ${escapeHTML(
                            selectedYear
                        )}

                        <span>→</span>

                        ${escapeHTML(
                            selectedSemester
                        )}

                        <span>→</span>

                        ${escapeHTML(
                            subject.code
                        )}

                    </div>

                </div>

            `;

        }


        scrollToResults();

        return;

    }


    /* -----------------------------------------------------
       PDF EXISTS
    ----------------------------------------------------- */

    if (elementExists(paperResults)) {

        paperResults.innerHTML = "";

    }


    papers.forEach(
        paper => {

            const card =
                document.createElement(
                    "article"
                );


            card.className =
                "paper-card";


            const safeFile =
                encodeURI(
                    paper.file
                );


            card.innerHTML = `

                <div class="paper-icon">
                    PDF
                </div>


                <div class="paper-info">

                    <div class="paper-meta">

                        <span>
                            ${escapeHTML(
                                paper.year
                            )}
                        </span>

                        <span>
                            ${escapeHTML(
                                paper.examType ||
                                "PYQ"
                            )}
                        </span>

                    </div>


                    <h3>
                        ${escapeHTML(
                            paper.title
                        )}
                    </h3>


                    <p>

                        ${escapeHTML(
                            subject.code
                        )}

                        •

                        ${escapeHTML(
                            subject.name
                        )}

                    </p>

                </div>


                <div class="paper-actions">

                    <a
                        href="${safeFile}"
                        target="_blank"
                        rel="noopener noreferrer"
                        class="view-pdf-button">

                        View PDF
                        ↗

                    </a>


                    <a
                        href="${safeFile}"
                        download
                        class="download-pdf-button">

                        Download
                        ↓

                    </a>

                </div>

            `;


            paperResults.appendChild(
                card
            );

        }
    );


    scrollToResults();

}


/* =========================================================
   SCROLL TO RESULTS
========================================================= */

function scrollToResults() {

    const resultsSection =
        document.getElementById(
            "resultsSection"
        );


    if (
        elementExists(resultsSection)
    ) {

        setTimeout(() => {

            resultsSection.scrollIntoView({

                behavior: "smooth",

                block: "center"

            });

        }, 100);

    }

}


/* =========================================================
   HTML ESCAPE
========================================================= */

function escapeHTML(value) {

    return String(value ?? "")
        .replace(
            /&/g,
            "&amp;"
        )
        .replace(
            /</g,
            "&lt;"
        )
        .replace(
            />/g,
            "&gt;"
        )
        .replace(
            /"/g,
            "&quot;"
        )
        .replace(
            /'/g,
            "&#039;"
        );

}


/* =========================================================
   TOAST
========================================================= */

function showToast(message) {

    const existing =
        document.querySelector(
            ".qbank-toast"
        );


    if (existing) {

        existing.remove();

    }


    const toast =
        document.createElement(
            "div"
        );


    toast.className =
        "qbank-toast";


    toast.innerHTML = `

        <span>!</span>

        ${escapeHTML(message)}

    `;


    document.body.appendChild(
        toast
    );


    setTimeout(() => {

        toast.classList.add(
            "show"
        );

    }, 20);


    setTimeout(() => {

        toast.classList.remove(
            "show"
        );


        setTimeout(() => {

            toast.remove();

        }, 300);

    }, 3000);

}


/* =========================================================
   NAVIGATION
========================================================= */

document
    .querySelectorAll(
        'a[href^="#"]'
    )
    .forEach(
        link => {

            link.addEventListener(
                "click",
                event => {

                    const href =
                        link.getAttribute(
                            "href"
                        );


                    if (
                        !href ||
                        href === "#"
                    ) {

                        return;

                    }


                    const target =
                        document.querySelector(
                            href
                        );


                    if (!target) {

                        return;

                    }


                    event.preventDefault();


                    target.scrollIntoView({

                        behavior: "smooth"

                    });

                }
            );

        }
    );


